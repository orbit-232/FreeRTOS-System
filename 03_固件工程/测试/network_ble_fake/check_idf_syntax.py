"""Syntax-check the production panel_ble.c with the official IDF headers.

This reuses the exact RISC-V compile command generated by ESP-IDF for
panel_ble.c, rewrites only the stale C:/wsp path prefix to this checkout, and
runs -fsyntax-only.  It does not configure CMake, link, flash or touch COM3.
"""
from __future__ import annotations

import json
import pathlib
import shlex
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
COMPILE_DB = ROOT / "build-apps-a2-rev1_3" / "compile_commands.json"
SOURCE = ROOT / "components" / "panel_network" / "src" / "panel_ble.c"


def rewrite(value: str) -> str:
    value = value.replace("C:/wsp/WavesharePanel/03_Firmware", ROOT.as_posix())
    value = value.replace(r"C:\wsp\WavesharePanel\03_Firmware", str(ROOT))
    value = value.replace("C:\\wsp\\WavesharePanel\\03_Firmware", str(ROOT))
    return value


def main() -> int:
    if not COMPILE_DB.exists():
        print(f"FAIL: compile database missing: {COMPILE_DB}", file=sys.stderr)
        return 1
    entries = json.loads(COMPILE_DB.read_text(encoding="utf-8"))
    matches = [entry for entry in entries if entry["file"].endswith("panel_ble.c")]
    if len(matches) != 1:
        print(f"FAIL: expected one panel_ble.c entry, got {len(matches)}", file=sys.stderr)
        return 1
    entry = matches[0]
    args = shlex.split(entry["command"], posix=False)
    args = [arg.replace('\\"', '"') for arg in args]
    args = [arg[1:-1] if arg.startswith('"') and arg.endswith('"') else arg for arg in args]
    args = [("@" + arg[2:-1]) if arg.startswith('@"') and arg.endswith('"') else arg
            for arg in args]

    cleaned: list[str] = []
    skip_next = False
    for arg in args:
        if skip_next:
            skip_next = False
            continue
        if arg in ("-o", "-MT", "-MF"):
            skip_next = True
            continue
        if arg in ("-MD", "-MMD", "-MP", "-c"):
            continue
        if arg.lower().endswith("panel_ble.c"):
            continue
        cleaned.append(rewrite(arg))
    cleaned += ["-fsyntax-only", str(SOURCE)]

    print(f"SYNTAX panel_ble.c: {SOURCE}")
    print(f"CWD {entry['directory']}")
    proc = subprocess.run(cleaned, cwd=entry["directory"], text=True)
    if proc.returncode != 0:
        print(f"FAIL: IDF syntax exit={proc.returncode}", file=sys.stderr)
        return proc.returncode
    print("PASS: panel_ble.c with official ESP-IDF 6.0.2 / esp_hosted 2.13.1 headers")
    return 0


if __name__ == "__main__":
    sys.exit(main())
